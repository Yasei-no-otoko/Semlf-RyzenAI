def _validate_graph_references(graph):
    """Check flat SSA/topology before following producer chains or reading weights."""
    for values, label in ((graph.input, "input"), (graph.output, "output"), (graph.initializer, "initializer"), (graph.node, "node")):
        names = [value.name for value in values]
        _require(all(names) and len(set(names)) == len(names), "Duplicate/empty " + label + " name")
    known = {v.name for v in graph.input} | {t.name for t in graph.initializer}
    for node in graph.node:
        _require(all(not name or name in known for name in node.input), "Undefined/non-topological input")
        for name in node.output:
            _require(not name or name not in known, "Duplicate SSA output")
            if name:
                known.add(name)
    _require(all(v.name in known for v in graph.output), "Missing graph output")


@contextmanager
def _work_directory(path):
    before = Path.cwd()
    try:
        os.chdir(path)
        yield
    finally:
        os.chdir(before)


def lower_token_graph(token_model: Path, output_dir: Path, *, profile: dict) -> dict:
    """Create a fresh token payload using the caller's pinned SDK/profile.

    SDK metadata may be normalized inside the new directory before publication.
    Existing directories, source files and completed manifests are never changed.
    """
    source_path, output = Path(token_model).resolve(strict=True), Path(output_dir).absolute()
    _require(not output.exists() and not output.is_symlink(), "Output directory must be new")
    _require(not output.resolve().is_relative_to(source_path.parent) and not source_path.parent.is_relative_to(output.resolve()),
             "Source and output directories must be disjoint")
    output = output.resolve()
    config = _contract(profile)
    source_hash = _sha(source_path)
    source = onnx.load(source_path, load_external_data=False)
    _validate_graph_references(source.graph)
    _require(not source.functions and not any(a.type in (onnx.AttributeProto.GRAPH, onnx.AttributeProto.GRAPHS) for n in source.graph.node for a in n.attribute),
             "Nested graphs/functions require a separate lowering contract")
    _require(len(source.graph.input) == config["input_count"] and len(source.graph.output) == config["output_count"], "Graph IO count differs")
    for values, prefix in ((source.graph.input, "past_key_values."), (source.graph.output, "present.")):
        state = [v for v in values if v.name.startswith(prefix)]
        _require(len(state) == config["state_tensor_count"] and all(v.type.tensor_type.elem_type == T.FLOAT16 for v in state), "State boundaries differ")
    values = {v.name: v for v in [*source.graph.input, *source.graph.output, *source.graph.value_info]}
    initializers = {t.name: t for t in source.graph.initializer}
    producers = {name: n for n in source.graph.node for name in n.output if name}
    original_names = set(values) | set(initializers) | set(producers) | {n.name for n in source.graph.node}
    _require(not any(name.startswith("__qwen35_") for name in original_names), "Source uses reserved generated names")
    _require(len(initializers) == len(source.graph.initializer), "Duplicate initializer name")
    _require(len(producers) == sum(bool(x) for n in source.graph.node for x in n.output), "Duplicate producer")
    expected = {"MatMulNBits": config["matmul_count"], "LinearAttention": config["linear_attention_count"]}
    for op, count in expected.items():
        _require(sum(n.op_type == op for n in source.graph.node) == count, "Unexpected node count: " + op)
    _require(not any(n.op_type == "DynamicDispatch" for n in source.graph.node), "Source is already lowered")
    _require(HOST_COUNT not in values and HOST_COUNT not in producers and HOST_COUNT not in initializers, "Host control name collision")
    count_name = config["host_count_tensor"]
    count = producers[count_name]
    _require(count.op_type == "ReduceSum" and count.domain == "" and len(count.input) == 2 and count.input[0] == "attention_mask" and
             _attrs(count) in ({"keepdims": 0}, {"keepdims": 0, "noop_with_empty_axes": 0}),
             "Host control must use the existing attention_mask sum")
    _require(values[count_name].type.tensor_type.elem_type == T.INT64 and _shape(values[count_name]) == [1], "Mask sum must be INT64[1]")
    axis, _ = _read_tensor(initializers[count.input[1]], source_path.parent, 8)
    _require(axis.dtype == np.int64 and axis.tolist() == [1], "Mask reduction must use axis1")
    _require(values["attention_mask"].type.tensor_type.elem_type == T.INT64, "Attention mask must be INT64")
    _require(values["logits"].type.tensor_type.elem_type == T.FLOAT16 and _shape(values["logits"]) == [1, 1, config["vocab_size"]], "Source logits contract differs")
    guards = {_external(t, source_path.parent)[0]: _stat(_external(t, source_path.parent)[0]) for t in source.graph.initializer if t.external_data}
    report = dict(schema_version=1, status="started", implementation_sha256=_sha(__file__),
        source_model=dict(path=str(source_path), sha256=source_hash),
        token_lowering=config, partitions=[], npu_execution=False, host_compile=False, ort_session=False)
    output.mkdir()
    (output / "cache").mkdir()
    try:
        with _work_directory(output):
            sdk = _sdk_api()
            nodes, extra_vis, extra_constants, metadata = [], [], [], {}
            removable, indices = set(), {"MatMulNBits": 0, "LinearAttention": 0}
            for node in source.graph.node:
                if node.op_type in expected:
                    index = indices[node.op_type]
                    if node.op_type == "MatMulNBits":
                        result = _lower_matmul(index, node, (source_path, source), values, initializers, output, config, sdk)
                        removable.update(n for n in node.input[1:] if n)
                    else:
                        result = _lower_la(index, node, source, values, producers, output, config, sdk)
                    new_nodes, vis, constants, row, meta = result
                    nodes.extend(new_nodes)
                    extra_vis.extend(vis)
                    extra_constants.extend(constants)
                    report["partitions"].append(row)
                    metadata[row["dd_node"]] = meta
                    indices[node.op_type] += 1
                    del result, new_nodes, vis, constants, meta
                    gc.collect()
                else:
                    nodes.append(copy.deepcopy(node))
                if count_name in node.output:
                    nodes.append(h.make_node("Cast", [count_name], [HOST_COUNT], name="__qwen35_host_count", to=T.UINT32))
            logits = [n for n in nodes if "logits" in n.output]
            _require(len(logits) == 1 and not any("logits" in n.input for n in nodes), "Logits must have one terminal producer")
            alias = "__qwen35_logits_fp16"
            logits[0].output[list(logits[0].output).index("logits")] = alias
            nodes.append(h.make_node("Cast", [alias], ["logits"], name="__qwen35_logits_float", to=T.FLOAT))
            extra_vis.extend([h.make_tensor_value_info(alias, T.FLOAT16, [1, 1, config["vocab_size"]]), h.make_tensor_value_info(HOST_COUNT, T.UINT32, [1])])
            model = copy.deepcopy(source)
            model.graph.ClearField("node")
            model.graph.node.extend(nodes)
            used = {n for node in nodes for n in node.input if n} | {v.name for v in model.graph.input}
            retained = [copy.deepcopy(t) for t in source.graph.initializer if t.name not in removable or t.name in used]
            model.graph.ClearField("initializer")
            model.graph.initializer.extend([*retained, *extra_constants])
            existing_values = {v.name for v in model.graph.value_info}
            for value in extra_vis:
                if value.name not in existing_values:
                    model.graph.value_info.append(value)
                    existing_values.add(value.name)
            for value in [*model.graph.output, *model.graph.value_info]:
                if value.name == "logits":
                    value.type.tensor_type.elem_type = T.FLOAT
            model.ClearField("opset_import")
            model.opset_import.extend(_opsets(source))
            # Preserve original non-target nodes exactly, including surrounding activations.
            named = {n.name: n for n in nodes}
            _require(len(named) == len(nodes), "Generated node name collision")
            for node in source.graph.node:
                if node.op_type not in expected:
                    original = copy.deepcopy(node)
                    if "logits" in original.output:
                        original.output[list(original.output).index("logits")] = alias
                    _require(named[node.name].SerializeToString() == original.SerializeToString(), "Non-target node changed")
            _require([v.SerializeToString() for v in model.graph.input] == [v.SerializeToString() for v in source.graph.input], "Input boundary changed")
            for before, after in zip(source.graph.output, model.graph.output, strict=True):
                expected_output = copy.deepcopy(before)
                if before.name == "logits":
                    expected_output.type.tensor_type.elem_type = T.FLOAT
                _require(after.SerializeToString() == expected_output.SerializeToString(), "Output/state boundary changed")
            _validate_graph_references(model.graph)
            final_values = {v.name: v for v in [*model.graph.input, *model.graph.output, *model.graph.value_info]}
            for node in nodes:
                if node.op_type != "DynamicDispatch":
                    continue
                a, meta = _attrs(node), metadata[node.name]
                _require(list(node.input[:-1]) == meta["op_list"][0]["in_args"] and node.input[-1] == HOST_COUNT and a["input_num"] == len(node.input)-1, "Host-only DD input contract differs")
                for label, names in (("input", node.input[:-1]), ("output", node.output)):
                    for i, name in enumerate(names):
                        info = meta["tensor_map"][name]
                        _require(info["dtype"] == "bfloat16" and final_values[name].type.tensor_type.elem_type == T.BFLOAT16 and
                                 info["shape"] == a[f"{label}_shape_{i}"] == _shape(final_values[name]), "DD dtype/shape contract differs")
            report["external_data"] = _pack_external(model, source_path.parent, output / "non_matmul_initializers.data")
            with (output / "model.onnx").open("xb") as stream:
                stream.write(model.SerializeToString())
            report["checker"] = _check_final_model(output / "model.onnx")
            _require(_sha(source_path) == source_hash and all(_stat(p) == state for p, state in guards.items()), "Source changed during lowering")
            report.update(status="lowered_cpu_checked", source_immutability_checked=True, non_target_nodes_preserved=True,
                state_io_preserved=True, logits="FLOAT via explicit Cast", artifacts=[dict(path=p.relative_to(output).as_posix(),
                    size=p.stat().st_size, sha256=_sha(p)) for p in sorted(output.rglob("*")) if p.is_file()],
                limitations=["CPU graph and metadata checks only; no combined-model or 16K runtime proof", "SDK schema check does not infer all custom operator semantics"])
    except Exception as exc:
        report.update(status="failed", error=dict(type=type(exc).__name__, message=str(exc)))
        raise
    finally:
        _write_json(output / "lowering-manifest.json", report)
    return report
