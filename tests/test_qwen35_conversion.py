"""Opt-in integration regression for the real tiny Quark Qwen3.5 checkpoint.

The fixture is deliberately cached, rather than committed: it is generated by
the public Quark API in ``cache/qwen35-conversion``.  Enable it only from the
isolated conversion environment with ``RUN_QWEN35_CONVERSION_INTEGRATION=1``.
It does not create a model, call model.generate, or use an NPU.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest


if os.environ.get("RUN_QWEN35_CONVERSION_INTEGRATION") != "1":
    pytest.skip("set RUN_QWEN35_CONVERSION_INTEGRATION=1 in the Quark conversion environment", allow_module_level=True)


torch = pytest.importorskip("torch")
pytest.importorskip("quark.torch")
quantized_model = pytest.importorskip("onnxruntime_genai.models.quantized_model")
safetensors = pytest.importorskip("safetensors")

from benchmarks.export_qwen35 import (  # noqa: E402
    LINEAR_PROJECTIONS,
    PUBLIC_OGA_014_QUANTIZED_MODEL_SHA256,
    qwen35_quark_adapter,
)
from benchmarks import quantize_qwen35  # noqa: E402


ROOT = Path(__file__).parents[1]
CHECKPOINT = ROOT / "cache" / "qwen35-conversion" / "tiny-qwen35-quark-rtn-g128-v2"


def _source_tensors() -> dict[str, object]:
    with safetensors.safe_open(CHECKPOINT / "model.safetensors", framework="pt") as archive:
        return {name: archive.get_tensor(name).clone() for name in archive.keys()}


def _projection_tensor(tensors: dict[str, object], prefix: str, *names: str):
    for name in names:
        key = prefix + name
        if key in tensors:
            return tensors[key]
    raise AssertionError(f"missing Quark tensor for {prefix}: {names}")


def _reference_ort_packing(model, tensors: dict[str, object], prefix: str):
    """Run the reviewed upstream unpack/repack on a physical Quark tensor."""

    reference = quantized_model.QuantizedTensorModule()
    reference.qweight = _projection_tensor(tensors, prefix, "weight", "qweight").clone()
    reference.scales = _projection_tensor(
        tensors, prefix, "weight_quantizer.scale", "weight_scale", "scales"
    ).clone()
    reference.qzeros = _projection_tensor(
        tensors, prefix, "weight_quantizer.zero_point", "weight_zero_point", "qzeros"
    ).clone()
    reference.bits = 4
    reference.group_size = 128
    reference.in_features = reference.qweight.shape[0]
    reference.out_features = reference.scales.shape[1]
    model.set_g_idx(reference)
    model.unpack(reference)
    model.repack(reference)
    return reference


def test_real_quark_qwen35_adapter_preserves_packed_projection_math_and_raw_linear_state():
    if not CHECKPOINT.is_dir():
        pytest.skip(f"create the tiny Quark fixture first: {CHECKPOINT}")

    config = json.loads((CHECKPOINT / "config.json").read_text(encoding="utf-8"))
    assert config["architectures"] == ["Qwen3_5ForConditionalGeneration"]
    assert config["text_config"]["model_type"] == "qwen3_5_text"
    assert config["quantization_config"]["global_quant_config"]["weight"]["dtype"] == "uint4"
    assert config["quantization_config"]["global_quant_config"]["weight"]["group_size"] == 128

    source = _source_tensors()
    assert source["model.language_model.embed_tokens.weight"].dtype is torch.bfloat16
    assert "lm_head.weight" in source  # Deliberately still a packed text projection.
    assert source["lm_head.weight"].dtype is torch.int32

    with qwen35_quark_adapter(PUBLIC_OGA_014_QUANTIZED_MODEL_SHA256):
        model = quantized_model.QuantModel.from_pretrained(
            "quark",
            input_path=str(CHECKPOINT),
            quant_attrs={"config": config["quantization_config"]},
            q_size=128,
            kv_size=128,
            intermediate_size=256,
            num_layers=4,
        )

    layers = {layer.layer_id: layer for layer in model.layers}
    assert set(layers) == {0, 1, 2, 3}
    assert layers[3].self_attn.q_proj.qweight is not None
    assert torch.equal(model.embedding.weight, source["model.language_model.embed_tokens.weight"])

    for layer_id in range(3):
        linear = layers[layer_id].linear_attn
        assert linear is not None
        base = f"model.language_model.layers.{layer_id}.linear_attn."
        assert torch.equal(linear.conv1d.weight, source[base + "conv1d.weight"])
        assert torch.equal(linear.A_log, source[base + "A_log"])
        assert torch.equal(linear.dt_bias, source[base + "dt_bias"])
        assert torch.equal(linear.norm.weight, source[base + "norm.weight"])
        for name in LINEAR_PROJECTIONS:
            prefix = base + name + "."
            expected = _reference_ort_packing(model, source, prefix)
            actual = getattr(linear, name)
            assert torch.equal(actual.qweight, expected.qweight)
            assert torch.equal(actual.scales, expected.scales)
            assert torch.equal(actual.qzeros, expected.qzeros)


def test_manifest_exclusions_match_the_live_quark_policy():
    """Record every module deliberately kept out of uint4 conversion."""

    config = quantize_qwen35._weight_only_config()
    assert tuple(config.exclude) == quantize_qwen35.QUARK_EXCLUDED_MODULES
    assert quantize_qwen35.QUARK_EXCLUDED_MODULES == (
        "model.visual.*",
        "mtp.*",
        "model.language_model.embed_tokens",
        "model.language_model.layers.*.linear_attn.conv1d",
    )
